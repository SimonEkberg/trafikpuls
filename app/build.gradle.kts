// The Trafiklab key is read from local.properties (git-ignored) or the environment (CI),
// so it never ends up in version control. An empty key starts the app in demo mode.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}
val trafiklabApiKey: String =
    (localProperties.getProperty("TRAFIKLAB_API_KEY") ?: System.getenv("TRAFIKLAB_API_KEY") ?: "")
        .trim()
        .replace("\"", "")

